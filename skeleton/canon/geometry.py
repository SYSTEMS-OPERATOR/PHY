    """Immutable instance of one supported SOPHY canon revision at scale ``H``."""

    height_mm: float
    canon_version: str
    canon_law_hash: str
    landmarks: Tuple[CanonicalLandmark, ...]

    @property
    def standing_height_mm(self) -> float:
        return self.height_mm

    @property
    def arm_span_mm(self) -> float:
        return self.height_mm

    @property
    def circle_radius_mm(self) -> float:
        return self.height_mm / 2.0

    def landmark(self, canonical_id: str) -> CanonicalLandmark:
        for landmark in self.landmarks:
            if landmark.canonical_id == canonical_id:
                return landmark
        raise KeyError(canonical_id)


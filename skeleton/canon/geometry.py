def golden_major(total: float) -> float:
    """Return the major segment of ``total`` under golden division."""

    return float(total) / PHI


def golden_minor(total: float) -> float:
    """Return the minor segment of ``total`` under golden division."""

    return float(total) / (PHI * PHI)


def golden_recurse(total: float, depth: int, branch: str = "major") -> float:
    """Apply one named golden-section branch repeatedly.

    This is a proportional operator, not an anatomical binding.  Binding its
    output to an identity landmark changes the canon and therefore requires an
    explicit canon revision.
    """

    if depth < 0:
        raise ValueError("depth must be non-negative")
    if branch not in {"major", "minor"}:
        raise ValueError("branch must be 'major' or 'minor'")
    value = float(total)
    operator = golden_major if branch == "major" else golden_minor
    for _ in range(depth):
        value = operator(value)
    return value



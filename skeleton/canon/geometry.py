class CanonIntegrityError(ValueError):
    """Raised when imported geometry is not an exact canon instantiation."""


@dataclass(frozen=True, slots=True)
class Point3:
    """Immutable right-handed XYZ point or vector."""

    x: float
    y: float
    z: float

    def scaled(self, factor: float) -> "Point3":
        return Point3(self.x * factor, self.y * factor, self.z * factor)

    def mirror_x(self) -> "Point3":
        return Point3(-self.x, self.y, self.z)

    def plus(self, other: "Point3") -> "Point3":
        return Point3(self.x + other.x, self.y + other.y, self.z + other.z)

    def as_list(self) -> list[float]:
        return [self.x, self.y, self.z]

    @classmethod
    def from_iterable(cls, values: Iterable[float]) -> "Point3":
        x, y, z = values
        return cls(float(x), float(y), float(z))


@dataclass(frozen=True, slots=True)
class CanonicalLandmark:
    """One immutable node in the normalized canonical landmark graph."""

    canonical_id: str
    family: str
    parent_frame: str
    side: str
    normalized: Point3
    coordinates_mm: Point3
    derivation_operator: str
    derivation_inputs: Tuple[str, ...]
    provenance: str
    tolerance_category: str = "canonical_exact"
    mirrored_from: Optional[str] = None
    downstream_dependents: Tuple[str, ...] = ()

    def to_dict(self) -> Dict[str, Any]:
        derivation: Dict[str, Any] = {
            "operator": self.derivation_operator,
            "inputs": list(self.derivation_inputs),
        }
        if self.mirrored_from is not None:
            derivation["mirrored_from"] = self.mirrored_from
        return {
            "canonical_id": self.canonical_id,
            "family": self.family,
            "parent_frame": self.parent_frame,
            "side": self.side,
            "normalized_coordinates_H": self.normalized.as_list(),
            "coordinates_mm": self.coordinates_mm.as_list(),
            "derivation": derivation,
            "provenance": self.provenance,
            "tolerance_category": self.tolerance_category,
            "downstream_dependents": list(self.downstream_dependents),
        }


@dataclass(frozen=True, slots=True)
class _LandmarkLaw:
    canonical_id: str
    family: str
    parent_frame: str
    side: str
    normalized: Point3
    downstream_dependents: Tuple[str, ...] = ()
    mirror_id: Optional[str] = None

    def manifest(self) -> Dict[str, Any]:
        result = {
            "canonical_id": self.canonical_id,
            "family": self.family,
            "parent_frame": self.parent_frame,
            "side": self.side,
            "normalized_coordinates_H": self.normalized.as_list(),
            "operator": "scale_normalized_by_H",
            "downstream_dependents": list(self.downstream_dependents),
        }
        if self.mirror_id is not None:
            result["mirror_id"] = self.mirror_id
        return result



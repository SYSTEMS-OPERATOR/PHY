"""Deterministic SOPHY whole-body geometry kernel.

This module defines identity geometry, not anthropometric approximation and not
project packaging.  Canonical coordinates are normalized to the master scale
``H`` and instantiated in millimetres.  Only right-side laws are authored;
left-side laws are generated by reflection through the midsagittal plane.
"""


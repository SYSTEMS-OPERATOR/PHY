import assert from 'node:assert/strict';
import fs from 'node:fs';
import { relationshipsForBone, relationshipsHtml } from '../src/relationships.js';

const graph=JSON.parse(fs.readFileSync(new URL('../dist/relationship_graph.json',import.meta.url),'utf8'));
const before=JSON.stringify(graph);
const mandible=relationshipsForBone(graph,'BONE_MANDIBLE');
const joints=mandible.filter(r=>r.kind==='qualitative_articulation');
assert.equal(joints.length,2);
assert.ok(joints.every(r=>r.participants.some(p=>p.bone_id==='BONE_MANDIBLE')&&r.engineering_definition===null));
const legacy=mandible.find(r=>r.kind==='legacy_articulation');
assert.equal(legacy.original_declaration.joint_type,'hinge');
assert.equal(legacy.participants[1].bone_id,null);
assert.deepEqual(legacy.participants[1].runtime_resolution.candidates,['BONE_TEMP_L','BONE_TEMP_R']);
assert.ok(relationshipsForBone(graph,'BONE_TEMP_R').includes(legacy));
const html=relationshipsHtml(graph,'BONE_MANDIBLE',new Set(['BONE_MANDIBLE']));
assert.match(html,/rotation, translation/);
assert.match(html,/unresolved \(null\)/);
assert.match(html,/Runtime legacy matching: ambiguous/);
assert.match(html,/data-related-bone="BONE_TEMP_L" disabled/);
assert.match(html,/Structural region membership/);
assert.match(html,/Operational signal links/);
assert.equal(JSON.stringify(graph),before,'inspection cannot mutate its graph');
const hyoid=relationshipsForBone(graph,'BONE_HYOID');
assert.deepEqual(hyoid.map(r=>[r.kind,r.resolution_status]),[['legacy_parent','unspecified']]);
const unsafe=structuredClone(graph);
const row=unsafe.relationships.find(r=>r.relationship_id===legacy.relationship_id);
row.original_declaration={bone:'<img src=x onerror="alert(1)">',joint_type:'<script>bad()</script>'};
row.provenance.source_ids={malformed:'retained diagnostic'};
const escaped=relationshipsHtml(unsafe,'BONE_MANDIBLE');
assert.ok(!escaped.includes('<img')&&!escaped.includes('<script>'));
assert.match(escaped,/&lt;img/);
console.log('Relationship roles, ambiguity, navigation availability, escaping and read-only inspection pass.');
